export type PixelPoint = { x: number; y: number };

export type PixelWord = {
  cols: number;
  rows: number;
  pixels: PixelPoint[];
};

const glyphWidth = (char: string) => (char === ' ' ? 4 : GLYPH_WIDTH);

function lineWidth(line: string): number {
  const chars = [...line];
  if (chars.length === 0) return 0;
  return chars.reduce((sum, char) => sum + glyphWidth(char), 0) + (chars.length - 1) * LETTER_GAP;
}

/**
 * Rasterises one or more lines into pixel coordinates.
 *
 * Lines are centred against the widest one, and pixels come back sorted by
 * column so a morph can resolve left to right.
 */
export function renderWord(lines: string[]): PixelWord {
  const upper = lines.map((line) => line.toUpperCase());
  const widths = upper.map(lineWidth);
  const cols = Math.max(...widths, 0);
  const rows = upper.length * GLYPH_HEIGHT + Math.max(upper.length - 1, 0) * LINE_GAP;
  const pixels: PixelPoint[] = [];

  upper.forEach((line, lineIndex) => {
    const originY = lineIndex * (GLYPH_HEIGHT + LINE_GAP);
    let originX = Math.round((cols - (widths[lineIndex] ?? 0)) / 2);

    for (const char of [...line]) {
      const glyph = GLYPHS[char] ?? GLYPHS[' ']!;
      glyph.forEach((row, y) => {
        [...row].forEach((cell, x) => {
          if (cell === '#') pixels.push({ x: originX + x, y: originY + y });
        });
      });
      originX += glyphWidth(char) + LETTER_GAP;
    }
  });

  pixels.sort((a, b) => a.x - b.x || a.y - b.y);

  return { cols, rows, pixels };
}
