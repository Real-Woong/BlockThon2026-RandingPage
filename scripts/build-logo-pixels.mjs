import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

/**
 * Traces the blockthon logo PNG into the cube lattice.
 *
 * Run by hand, not by the build: `node scripts/build-logo-pixels.mjs`. It writes
 * `lib/logoLockup.ts`, which is committed. The field builds its cube pool
 * synchronously during render and the pool's size decides how many elements get
 * mounted, so the trace cannot happen at runtime — an async decode would mean
 * re-mounting the whole pool once the image landed, and the project is a static
 * export, so the first frame would ship with an empty field.
 *
 * The trace is binary: alpha only, RGB discarded. A cell is either a cube or
 * empty. The source strokes are three different blues, but the field renders
 * one material, and tonal steps at this cube size read as dirt rather than as
 * depth.
 *
 * Source is the horizontal lockup, not the stacked one, and that is geometry
 * rather than taste. The word band is wide and short, so art in it is limited
 * by width; the height it then takes is `rows/cols × maxWidth`, which depends
 * only on the source's aspect ratio — the trace resolution cancels out. The
 * stacked lockup is 1.27:1 and would need a 944px band at every resolution.
 * The horizontal lockup is 5.82:1 and needs 166px, and the band is already 280.
 */

const SOURCE = 'image_source/2.png';
const OUT = 'lib/logoLockup.ts';

/** Anything more transparent than this is background. */
const ALPHA_CUTOFF = 8;
/** Share of a cell that must be ink before it becomes a cube. */
const COVERAGE = 0.35;

/*
 * Two resolutions, because they are legible at different things.
 *
 * Width-bound art is always ~1066px across, so `cols` only decides how big one
 * cube is: 1066/cols. At 160 the tagline resolves; below about 128 it collapses
 * into noise. At 96 the tagline is gone but the cubes are half again as big,
 * which is the better trade on a phone, where the lockup is a third of the
 * width and the tagline could not be read at any resolution.
 */
const VARIANTS = [
  { name: 'WIDE', cols: 160 },
  { name: 'COMPACT', cols: 96 },
];

const image = sharp(SOURCE).ensureAlpha();
const { data, info } = await image.raw().toBuffer({ resolveWithObject: true });
const { width, height, channels } = info;

const alphaAt = (x, y) => data[(y * width + x) * channels + 3] ?? 0;

// Trim the transparent margin, so the grid is the artwork and nothing else.
let minX = width;
let minY = height;
let maxX = -1;
let maxY = -1;

for (let y = 0; y < height; y += 1) {
  for (let x = 0; x < width; x += 1) {
    if (alphaAt(x, y) <= ALPHA_CUTOFF) continue;
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
}

if (maxX < minX || maxY < minY) throw new Error(`${SOURCE} has no opaque pixels.`);

const contentWidth = maxX - minX + 1;
const contentHeight = maxY - minY + 1;

function trace(cols) {
  const rows = Math.round(cols * (contentHeight / contentWidth));
  const grid = [];
  let ink = 0;

  for (let gridY = 0; gridY < rows; gridY += 1) {
    const y0 = minY + Math.floor((gridY / rows) * contentHeight);
    const y1 = minY + Math.ceil(((gridY + 1) / rows) * contentHeight);
    let row = '';

    for (let gridX = 0; gridX < cols; gridX += 1) {
      const x0 = minX + Math.floor((gridX / cols) * contentWidth);
      const x1 = minX + Math.ceil(((gridX + 1) / cols) * contentWidth);
      let filled = 0;
      let total = 0;

      for (let y = y0; y < y1; y += 1) {
        for (let x = x0; x < x1; x += 1) {
          total += 1;
          if (alphaAt(x, y) > ALPHA_CUTOFF) filled += 1;
        }
      }

      const on = (total > 0 ? filled / total : 0) >= COVERAGE;
      if (on) ink += 1;
      row += on ? '#' : '.';
    }

    grid.push(row);
  }

  return { cols, rows, ink, grid };
}

const traced = VARIANTS.map((variant) => ({ ...variant, ...trace(variant.cols) }));

const banner = traced
  .map((v) => ` *   ${v.name.padEnd(7)} ${v.cols}×${v.rows}, ${v.ink} cubes`)
  .join('\n');

const body = traced
  .map(
    (v) => `const ${v.name}: string[] = [\n${v.grid.map((row) => `  '${row}',`).join('\n')}\n];`,
  )
  .join('\n\n');

writeFileSync(
  OUT,
  `/**
 * The blockthon lockup, traced onto the cube lattice.
 *
 * GENERATED by scripts/build-logo-pixels.mjs from ${SOURCE}. Do not edit by
 * hand — re-run the script when the logo changes.
 *
 * Binary: '#' is a cube, '.' is empty. The source's three blues are discarded,
 * because the field renders one material.
 *
${banner}
 */

import type { PixelPoint, PixelWord } from './pixelFont';

${body}

function render(grid: string[]): PixelWord {
  const pixels: PixelPoint[] = [];

  grid.forEach((row, y) => {
    [...row].forEach((cell, x) => {
      if (cell === '#') pixels.push({ x, y });
    });
  });

  // Sorted by column like renderWord, so a morph resolves left to right.
  pixels.sort((a, b) => a.x - b.x || a.y - b.y);

  return { cols: grid[0]?.length ?? 0, rows: grid.length, pixels };
}

export const renderLockup = () => render(WIDE);
export const renderLockupCompact = () => render(COMPACT);
`,
  'utf8',
);

console.log(`${SOURCE}  ink bbox ${contentWidth}×${contentHeight} (${(contentWidth / contentHeight).toFixed(2)}:1)`);
traced.forEach((v) => console.log(`  ${v.name.padEnd(7)} ${v.cols}×${v.rows}  ${v.ink} cubes`));
console.log(`wrote ${OUT}`);
